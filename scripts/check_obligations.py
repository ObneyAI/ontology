#!/usr/bin/env python3
"""Check the reviewed spec-to-test ledger against a fresh Allium plan.

This checks traceability, not semantic correctness of the human-reviewed mapping.
The Clojure suite executes the referenced assertions separately.
"""
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / 'specs/ontology.allium'

def verify():
    ledger = json.loads((ROOT / 'specs/test-coverage.json').read_text())
    assert ledger['spec_sha256'] == hashlib.sha256(SPEC.read_bytes()).hexdigest(), 'Spec changed: review and update coverage ledger'
    plan = json.loads(subprocess.check_output(['allium', 'plan', 'specs/ontology.allium'], cwd=ROOT, text=True))
    expected = {o['id'] for o in plan['obligations']}
    prose = {'prose.' + n for n in re.findall(r'@(?:invariant|guarantee)\s+(\w+)', SPEC.read_text())}
    expected |= prose
    rows = ledger['obligations']
    assert set(rows) == expected, f'Coverage mismatch: missing={expected-set(rows)}, obsolete={set(rows)-expected}'
    tests = {}
    for path in (ROOT / 'test/ai/obney/ontology').glob('*_test.clj'):
        source = path.read_text()
        ns = re.search(r'\(ns\s+(\S+)', source)[1]
        for match in re.finditer(r'\(deftest\s+(\S+)', source):
            tests[ns + '/' + match[1]] = (path.relative_to(ROOT), source[:match.start()].count('\n') + 1)
    for id, row in rows.items():
        assert row['tests'] and row['review'].strip(), f'Empty evidence: {id}'
        assert set(row['tests']) <= tests.keys(), f'Missing test in {id}: {set(row["tests"])-tests.keys()}'
    if '--markdown' in sys.argv:
        print('# Reviewed Allium test obligations\n')
        print('Generated by `python3 scripts/check_obligations.py --markdown`. The ledger binds to the spec hash and checks a fresh Allium plan. References establish traceability; passing tests and review establish evidence for behavior.\n')
        print('| Obligation | Executable witnesses | Review and representation |\n| --- | --- | --- |')
        for id, row in rows.items():
            links = ', '.join(f'[{name.split("/")[1]}](../{tests[name][0]}#L{tests[name][1]})' for name in row['tests'])
            print(f'| {id} | {links} | {row["review"]} |')
    else:
        print(json.dumps({'generated_obligations': len(plan['obligations']), 'prose_obligations': len(prose), 'mapped': len(rows), 'referenced_tests': len({t for r in rows.values() for t in r['tests']}), 'status': 'pass'}))

if __name__ == '__main__':
    try:
        verify()
    except (AssertionError, KeyError, subprocess.CalledProcessError) as error:
        sys.exit(str(error))
